"""Synthetic training data, so the project runs with no download.

IMPORTANT: this data is generated by code that follows patterns I wrote down. A model trained on it
will score very high because it has learned my patterns, which says little about real-world
accuracy. Train on a real labelled list (see README) before quoting any numbers.
A share of "hard" examples (clean-looking phishing, messy-looking legitimate links) is mixed in so
the problem is not trivially separable.
"""
from __future__ import annotations

import random
import string

from .features import BRANDS, KEYWORDS, RISKY_TLDS

WORDS = ["river", "stone", "bright", "cloud", "maple", "orbit", "pixel", "harbor", "cedar", "lumen", "north",
         "delta", "quartz", "willow", "summit", "nimbus", "forge", "atlas", "ember", "tidal", "garden", "studio"]
GOOD_TLDS = ["com", "org", "net", "io", "edu", "co.uk", "dev", "info"]
PATHS = ["", "/", "/about", "/blog/{w}-{w}", "/products/{w}", "/docs/{w}/intro", "/news/2026/{w}-{w}", "/contact"]


def _rand(rng, n):
    return "".join(rng.choice(string.ascii_lowercase + string.digits) for _ in range(n))


def benign(rng: random.Random) -> str:
    host = rng.choice(WORDS) + rng.choice(["", "-" + rng.choice(WORDS)]) + "." + rng.choice(GOOD_TLDS)
    if rng.random() < 0.35:
        host = rng.choice(["www", "blog", "docs", "shop", "mail"]) + "." + host
    url = ("https://" if rng.random() < 0.85 else "http://") + host + rng.choice(PATHS).format(w=rng.choice(WORDS))
    if rng.random() < 0.10:  # small legitimate sites also use cheap endings
        url = url.replace("." + host.rsplit(".", 1)[-1] + "/", "." + rng.choice(["xyz", "top", "click"]) + "/", 1)
    if rng.random() < 0.15:  # ordinary pages that mention account words or brands
        url += rng.choice(["/support", "/account/settings", "/help/verify-your-email", "/pricing/paypal-integration"])
    if rng.random() < 0.08:  # hard benign: tracking parameters, long paths, a login page on a real site
        url += "/account/login?" + "&".join(f"utm_{k}={_rand(rng, 8)}" for k in ("source", "medium", "campaign"))
    return url


def phishing(rng: random.Random) -> str:
    brand, kw = rng.choice(BRANDS), rng.choice(KEYWORDS)
    style = rng.randrange(7)
    if rng.random() < 0.30:   # subtle phishing: ordinary-looking domain, no scary words in the host
        host = rng.choice(WORDS) + _rand(rng, 3) + "." + rng.choice(GOOD_TLDS)
        return f"https://{host}/{rng.choice(['secure', 'auth', 'portal', 'id'])}/{_rand(rng, 6)}?ref={brand}"
    scheme = "https://" if rng.random() < 0.6 else "http://"
    tld = rng.choice(sorted(RISKY_TLDS))
    if style == 0:    # IP address host
        host = ".".join(str(rng.randint(1, 254)) for _ in range(4))
        return f"http://{host}/{brand}/{kw}.php?id={_rand(rng, 10)}"
    if style == 1:    # brand as subdomain of a throw-away domain
        return f"{scheme}{brand}.{kw}.{rng.choice(WORDS)}-{_rand(rng, 4)}.{tld}/{kw}/index.html"
    if style == 2:    # hyphenated look-alike
        return f"{scheme}{brand}-{kw}-{rng.choice(WORDS)}.{tld}/{_rand(rng, 12)}"
    if style == 3:    # '@' trick
        return f"{scheme}{brand}.com@{rng.choice(WORDS)}-{_rand(rng, 5)}.{tld}/{kw}"
    if style == 4:    # stacked subdomains
        return f"{scheme}{kw}.{brand}.{rng.choice(WORDS)}.{_rand(rng, 6)}.{rng.choice(GOOD_TLDS[:3])}/{kw}?session={_rand(rng, 24)}"
    if style == 5:    # punycode
        return f"{scheme}xn--{brand}-{_rand(rng, 5)}.{tld}/{kw}/"
    # hard phishing: a clean-looking domain (a "hacked" site) with a login page buried inside
    host = rng.choice(WORDS) + rng.choice(WORDS) + "." + rng.choice(GOOD_TLDS)
    return f"https://{host}/wp-content/{kw}/{brand}/{kw}.php"


def generate(n: int = 4000, seed: int = 7) -> list[tuple[str, int]]:
    """Return ``n`` (url, label) pairs, half phishing (1) and half legitimate (0)."""
    rng = random.Random(seed)
    rows = [(benign(rng), 0) for _ in range(n // 2)] + [(phishing(rng), 1) for _ in range(n - n // 2)]
    # real labelled lists contain mistakes, so flip about 3% of labels
    rows = [(u, 1 - l if rng.random() < 0.03 else l) for u, l in rows]
    rng.shuffle(rows)
    return rows
