#!/usr/bin/env python3
"""Phishing URL detector command line.

  python cli.py train [--csv urls.csv] [--out models/model.joblib]
  python cli.py check "http://paypal.secure-login.xyz/verify"
  python cli.py check --file urls.txt
"""
from __future__ import annotations

import argparse
import os
import sys

from phishing import data, model, synth

DEFAULT_MODEL = os.path.join("models", "model.joblib")


def cmd_train(args) -> int:
    if args.csv:
        rows = data.load_csv(args.csv, args.url_col, args.label_col)
        source = f"{args.csv} (real data)"
    else:
        rows = synth.generate(args.n)
        source = "SYNTHETIC data generated by this project"
    bad = sum(l for _, l in rows)
    print(f"Training on {len(rows)} URLs from {source}: {bad} phishing, {len(rows) - bad} legitimate.")
    res = model.train(rows)
    print(f"Split: {res['n_train']} for training, {res['n_test']} held back for testing.\n")
    print(f"{'model':<22}{'precision':>10}{'recall':>9}{'F1':>7}   caught  false-alarms  missed")
    for name, key in (("Random forest", "forest"), ("Logistic regression", "baseline")):
        m = res[key]
        print(f"{name:<22}{m['precision']:>10.3f}{m['recall']:>9.3f}{m['f1']:>7.3f}   {m['tp']:>6}  {m['fp']:>12}  {m['fn']:>6}")
    print("\nMost useful clues for the forest:")
    for name, imp in res["importances"][:8]:
        print(f"  {name:<22}{imp:.3f}")
    if not args.csv:
        print("\nNOTE: these scores are on synthetic data and mostly show that the model learned the patterns "
              "the generator writes. Train with --csv on a real labelled list before trusting any number.")
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    model.save(res["model"], args.out)
    print(f"\nSaved model to {args.out}")
    return 0


def cmd_check(args) -> int:
    if not os.path.exists(args.model):
        print(f"No model at {args.model}. Run: python cli.py train")
        return 2
    mdl = model.load(args.model)
    urls = list(args.url)
    if args.file:
        with open(args.file, encoding="utf-8") as fh:
            urls += [ln.strip() for ln in fh if ln.strip() and not ln.startswith("#")]
    if not urls:
        print("Give a URL, or --file with one URL per line.")
        return 2
    for u in urls:
        r = model.check(mdl, u, args.threshold)
        print(f"{r['verdict']:<11} {r['phishing_probability']:.0%}  {u}")
        for why in r["reasons"]:
            print(f"            - {why}")
    return 0


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Phishing URL detector")
    sub = p.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("train", help="train and evaluate a model")
    t.add_argument("--csv", help="real labelled data (columns like url,label)")
    t.add_argument("--url-col"); t.add_argument("--label-col")
    t.add_argument("--n", type=int, default=4000, help="size of synthetic data when no --csv (default 4000)")
    t.add_argument("--out", default=DEFAULT_MODEL)
    t.set_defaults(fn=cmd_train)
    c = sub.add_parser("check", help="score URLs (nothing is ever visited)")
    c.add_argument("url", nargs="*")
    c.add_argument("--file")
    c.add_argument("--model", default=DEFAULT_MODEL)
    c.add_argument("--threshold", type=float, default=0.5, help="phishing probability cut-off (default 0.5)")
    c.set_defaults(fn=cmd_check)
    args = p.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
